function q(
  sub: string,
  dom: string,
  text: string,
  A: string,
  B: string,
  C: string,
  D: string,
  ans: "A" | "B" | "C" | "D",
  exp: string,
  trap: string,
  time: number = 60
): SeedQuestion {
  const letters = ["A", "B", "C"] as const;
  const dist: Record<string, string> = {};
  for (const l of letters) {
    if (l === ans) {
      dist[l] = `Correct. ${exp}`;
    } else {
      dist[l] = `Incorrect. Common distractor based on: ${trap}`;
    }
  }
  return {
    exam_name: "CFA Level 1",
    subject: sub,
    skill_domain: dom,
    difficulty_tier: 2,
    question_text: text,
    options: { A, B, C, D },
    correct_option: ans,
    explanation: exp,
    distractor_analysis: dist as any,
    misconception: trap,
    time_estimate_seconds: time,
  };
}

